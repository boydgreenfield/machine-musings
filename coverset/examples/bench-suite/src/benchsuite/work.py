"""CPU burner plus a few tiny pure functions for the synthetic bench suite.

Generated by coverset's ``scripts/gen_bench_suite.py``; do not edit by hand.

``busy(ms)`` runs a deterministic integer workload whose size is calibrated once at
import time, so a test that calls ``busy(150)`` costs roughly 150 ms of CPU on whatever
machine (or sandbox) imports this module. Calibration runs the same loop as ``busy``,
so tracing overhead present at import time is folded into the rate.
"""

from __future__ import annotations

import math
import time

_CALIBRATION_ROUNDS = 20_000
_CALIBRATION_REPEATS = 5


def _spin(rounds: int) -> int:
    """Run ``rounds`` iterations of a 32-bit LCG/xorshift mix and return the state."""
    acc = 0x9E3779B9
    for i in range(rounds):
        acc = (acc * 1103515245 + i) & 0xFFFFFFFF
        acc ^= acc >> 13
    return acc


def _calibrate() -> float:
    """Return how many ``_spin`` rounds fit in one millisecond (best of a few repeats)."""
    best = math.inf
    for _ in range(_CALIBRATION_REPEATS):
        start = time.perf_counter()
        _spin(_CALIBRATION_ROUNDS)
        best = min(best, time.perf_counter() - start)
    return _CALIBRATION_ROUNDS / max(best * 1000.0, 1e-6)


ROUNDS_PER_MS: float = _calibrate()


def busy(ms: float) -> int:
    """Burn roughly ``ms`` milliseconds of CPU and return the workload's final state."""
    if ms <= 0:
        return 0
    return _spin(max(1, round(ms * ROUNDS_PER_MS)))


def checksum(data: bytes) -> int:
    """Return the Adler-32 checksum of ``data`` (matches ``zlib.adler32``)."""
    a, b = 1, 0
    for byte in data:
        a = (a + byte) % 65521
        b = (b + a) % 65521
    return (b << 16) | a


def collatz_steps(n: int) -> int:
    """Return the number of Collatz steps needed to reach 1 from ``n``."""
    if n < 1:
        raise ValueError("n must be a positive integer")
    steps = 0
    while n != 1:
        n = n // 2 if n % 2 == 0 else 3 * n + 1
        steps += 1
    return steps


def primes_below(n: int) -> list[int]:
    """Return all primes strictly less than ``n`` (sieve of Eratosthenes)."""
    if n < 3:
        return []
    sieve = bytearray([1]) * n
    sieve[0] = sieve[1] = 0
    for p in range(2, math.isqrt(n - 1) + 1):
        if sieve[p]:
            sieve[p * p :: p] = bytes(len(range(p * p, n, p)))
    return [i for i, flag in enumerate(sieve) if flag]


def run_length(text: str) -> list[tuple[str, int]]:
    """Run-length encode ``text`` as ``(character, count)`` pairs."""
    runs: list[tuple[str, int]] = []
    for ch in text:
        if runs and runs[-1][0] == ch:
            runs[-1] = (ch, runs[-1][1] + 1)
        else:
            runs.append((ch, 1))
    return runs
