def _assertion(index: int) -> tuple[str, str, frozenset[str]]:
    """Return (work function used, assertion source, extra stdlib imports) for test ``index``.

    Each assertion is a property that holds for every input, checked against an
    independent oracle where one exists, so generated tests always pass.
    """
    kind = index % 4
    if kind == 0:
        data = f'b"benchsuite:{index:05d}" * {index % 7}'
        return "checksum", f"assert checksum({data}) == zlib.adler32({data})", frozenset({"zlib"})
    if kind == 1:
        n = 1 + (index * 37) % 997
        return "collatz_steps", f"assert collatz_steps(2 * {n}) == collatz_steps({n}) + 1", frozenset()
    if kind == 2:
        n = 2 + (index * 53) % 300
        oracle = f"[k for k in range(2, {n}) if all(k % d for d in range(2, math.isqrt(k) + 1))]"
        return "primes_below", f"assert primes_below({n}) == {oracle}", frozenset({"math"})
    letters = "xyzw"[: 1 + (index // 4) % 4]
    text = "".join(ch * (1 + (index + j) % 3) for j, ch in enumerate(letters))
    source = f'assert "".join(ch * count for ch, count in run_length("{text}")) == "{text}"'
    return "run_length", source, frozenset()


def render_test_file(file_no: int, n_files: int, first_index: int, durations: Sequence[int]) -> str:
    """Render one ``tests/test_bench_NN.py`` holding ``len(durations)`` tests."""
    width = max(3, len(str(len(durations))))
    file_tag = f"{file_no:0{max(2, len(str(n_files)))}d}"
    used_funcs: set[str] = {"busy"}
    stdlib: set[str] = set()
    bodies: list[str] = []
    for offset, ms in enumerate(durations):
        func, assertion, extra = _assertion(first_index + offset)
        used_funcs.add(func)
        stdlib |= extra
        bodies.append(
            f"def test_{file_tag}_{offset + 1:0{width}d}() -> None:\n    busy({ms})\n    {assertion}\n"
        )
    header = [
        f'"""Synthetic bench tests, file {file_tag} of {n_files} '
        f'(generated by scripts/gen_bench_suite.py; do not edit)."""',
        "",
    ]
    header += [f"import {mod}" for mod in sorted(stdlib)]
    if stdlib:
        header.append("")
    header.append(f"from benchsuite.work import {', '.join(sorted(used_funcs))}")
    return "\n".join(header) + "\n\n\n" + "\n\n".join(bodies)


def render_readme(params: BenchParams, durations: Sequence[int], counts: Sequence[int]) -> str:
    """Render the suite's README with its parameters and expected serial runtime."""
    total_s = sum(durations) / 1000.0
    mean = sum(durations) / len(durations)
    per_file = f"{counts[0]}" if min(counts) == max(counts) else f"{min(counts)}-{max(counts)}"
    return f"""\
# benchsuite (synthetic)

**This suite is synthetic.** It is generated by `scripts/gen_bench_suite.py` in the coverset
repository and exists only to measure how test wall time scales when coverset fans a suite
out across shards. Its numbers are always labelled synthetic; do not read anything into the
code beyond that.

Each test calls `busy(ms)`, which burns roughly `ms` milliseconds of CPU with a deterministic
integer loop calibrated at import time, then asserts a property of one of four tiny pure
functions in `src/benchsuite/work.py` (`checksum`, `collatz_steps`, `primes_below`,
`run_length`) so that coverage has real source lines to record.

## Parameters

| parameter | value |
| --- | --- |
| tests | {params.tests} |
| files | {params.files} ({per_file} tests per file) |
| seed | {params.seed} |
| duration distribution | lognormal, mean {params.mean_ms:g} ms, sigma {params.sigma:g} |
| clamp | [{params.min_ms}, {params.max_ms}] ms, rounded to 1 ms |
| drawn mean | {mean:.1f} ms |
| min / max drawn | {min(durations)} ms / {max(durations)} ms |

**Expected serial runtime: {total_s:.1f} s** (sum of the drawn `busy()` durations; real runs
add pytest and interpreter overhead on top).

## Use

```sh
# regenerate (byte-identical for the same arguments)
uv run python scripts/gen_bench_suite.py --out examples/bench-suite --tests {params.tests} \\
  --files {params.files} --seed {params.seed} --mean-ms {params.mean_ms:g} --sigma {params.sigma:g} \\
  --min-ms {params.min_ms} --max-ms {params.max_ms}

# run one file locally
uv run --project examples/bench-suite python -m pytest -q tests/test_bench_01.py
```

coverset uses it like this: `uv run python scripts/bench_modal.py` fans this suite out across
1, 16 and 32 Modal sandboxes and records the wall times in `docs/benchmarks.md`.
"""


def render(params: BenchParams) -> tuple[dict[str, str], list[int]]:
    """Render every generated file as ``{relative path: content}`` plus the drawn durations."""
    params.validate()
    durations = draw_durations(params)
    counts = split_counts(params.tests, params.files)
    width = max(2, len(str(params.files)))
    files: dict[str, str] = {
        "pyproject.toml": PYPROJECT,
        ".gitignore": GITIGNORE,
        "README.md": render_readme(params, durations, counts),
        "src/benchsuite/__init__.py": INIT_PY,
        "src/benchsuite/work.py": WORK_PY,
        "tests/conftest.py": CONFTEST_PY,
    }
    start = 0
    for file_no, count in enumerate(counts, start=1):
        name = f"tests/{TEST_FILE_PREFIX}{file_no:0{width}d}.py"
        files[name] = render_test_file(file_no, params.files, start, durations[start : start + count])
        start += count
    return files, durations


def generate(out: Path, params: BenchParams) -> Summary:
    """Write the suite into ``out``, removing stale ``tests/test_bench_*.py`` files.

    Anything else already in ``out`` (``uv.lock``, ``.venv``) is left untouched.
    """
    files, durations = render(params)
    out.mkdir(parents=True, exist_ok=True)
    wanted = {out / rel for rel in files}
    tests_dir = out / "tests"
    if tests_dir.is_dir():
        for stale in tests_dir.glob(f"{TEST_FILE_PREFIX}*.py"):
            if stale not in wanted:
                stale.unlink()
    for rel, content in files.items():
        path = out / rel
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(content, encoding="utf-8", newline="\n")
    return Summary(out=out, files_written=len(files), tests=len(durations), durations_ms=tuple(durations))


def parse_args(argv: Sequence[str] | None = None) -> tuple[Path, BenchParams]:
    """Parse the command line into an output directory and generation parameters."""
    defaults = BenchParams()
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--out", type=Path, default=DEFAULT_OUT, help="output directory")
    parser.add_argument("--tests", type=int, default=defaults.tests, help="total number of tests")
    parser.add_argument("--files", type=int, default=defaults.files, help="number of test files")
    parser.add_argument("--seed", type=int, default=defaults.seed, help="random seed for durations")
    parser.add_argument("--mean-ms", type=float, default=defaults.mean_ms, help="lognormal mean (ms)")
    parser.add_argument("--sigma", type=float, default=defaults.sigma, help="lognormal sigma")
    parser.add_argument("--min-ms", type=int, default=defaults.min_ms, help="lower clamp (ms)")
    parser.add_argument("--max-ms", type=int, default=defaults.max_ms, help="upper clamp (ms)")
    ns = parser.parse_args(argv)
    params = BenchParams(
        tests=ns.tests,
        files=ns.files,
        seed=ns.seed,
        mean_ms=ns.mean_ms,
        sigma=ns.sigma,
        min_ms=ns.min_ms,
        max_ms=ns.max_ms,
    )
    try:
        params.validate()
    except ValueError as exc:
        parser.error(str(exc))
    return ns.out, params


def main(argv: Sequence[str] | None = None) -> int:
    """CLI entry point: generate the suite and print a one-line summary."""
    out, params = parse_args(argv)
    summary = generate(out, params)
    print(
        f"wrote {summary.files_written} files ({summary.tests} tests in {params.files} test files) "
        f"to {summary.out}; expected serial runtime {summary.total_seconds:.1f} s"
    )
    return 0


if __name__ == "__main__":
    sys.exit(main())
