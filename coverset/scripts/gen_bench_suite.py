"""Generate the synthetic pytest suite used for coverset's parallel fan-out benchmarks.

The output is a standalone uv project (``benchsuite``) whose tests each burn a fixed amount
of CPU drawn from a seeded lognormal distribution and then assert a property of a small
pure-function library, so that the tests exercise real source code under coverage. The
suite exists only to measure how test wall time scales with the number of shards; it is
synthetic and labelled as such everywhere it is used.

Output is byte-identical for identical arguments: durations come from
``random.Random(seed)``, everything else is derived from the test index.

Usage::

    uv run python scripts/gen_bench_suite.py [--out examples/bench-suite] [--tests 1200]
        [--files 24] [--seed 7] [--mean-ms 150] [--sigma 0.6] [--min-ms 50] [--max-ms 400]

Only stdlib is used so the script runs under any Python 3.12+ interpreter.
"""

from __future__ import annotations

import argparse
import math
import random
import sys
from collections.abc import Sequence
from dataclasses import dataclass
from pathlib import Path

DEFAULT_OUT = Path(__file__).resolve().parent.parent / "examples" / "bench-suite"
TEST_FILE_PREFIX = "test_bench_"


@dataclass(frozen=True)
class BenchParams:
    """Parameters that fully determine the generated suite."""

    tests: int = 1200
    files: int = 24
    seed: int = 7
    mean_ms: float = 150.0
    sigma: float = 0.6
    min_ms: int = 50
    max_ms: int = 400

    def validate(self) -> None:
        """Raise ``ValueError`` if the parameters cannot produce a sensible suite."""
        if self.tests < 1:
            raise ValueError("--tests must be at least 1")
        if not 1 <= self.files <= self.tests:
            raise ValueError("--files must be between 1 and --tests")
        if self.mean_ms <= 0:
            raise ValueError("--mean-ms must be positive")
        if self.sigma < 0:
            raise ValueError("--sigma must be non-negative")
        if not 0 <= self.min_ms <= self.max_ms:
            raise ValueError("need 0 <= --min-ms <= --max-ms")


@dataclass(frozen=True)
class Summary:
    """What a generation run produced."""

    out: Path
    files_written: int
    tests: int
    durations_ms: tuple[int, ...]

    @property
    def total_seconds(self) -> float:
        """Expected serial runtime of all ``busy()`` calls, in seconds."""
        return sum(self.durations_ms) / 1000.0


def draw_durations(params: BenchParams) -> list[int]:
    """Draw one CPU duration (ms) per test from a clamped lognormal.

    ``mean_ms`` is the arithmetic mean of the unclamped lognormal, so the underlying
    normal has ``mu = ln(mean_ms) - sigma**2 / 2``. Each draw is clamped to
    ``[min_ms, max_ms]`` and rounded to whole milliseconds.
    """
    rng = random.Random(params.seed)
    mu = math.log(params.mean_ms) - params.sigma**2 / 2
    durations: list[int] = []
    for _ in range(params.tests):
        raw = rng.lognormvariate(mu, params.sigma)
        clamped = min(max(raw, params.min_ms), params.max_ms)
        durations.append(round(clamped))
    return durations


def split_counts(tests: int, files: int) -> list[int]:
    """Split ``tests`` across ``files`` as evenly as possible (earlier files get the remainder)."""
    base, extra = divmod(tests, files)
    return [base + (1 if i < extra else 0) for i in range(files)]


