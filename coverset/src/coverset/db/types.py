"""Column types and id helpers shared by the models and the migrations.

Migrations import this module by its full path (``coverset.db.types``) so that autogenerated
revisions render custom types without hand edits.
"""

from __future__ import annotations

import os
import time
from datetime import UTC, datetime
from typing import Any, get_args

from sqlalchemy import BigInteger, DateTime, Dialect, Enum
from sqlalchemy.types import TypeDecorator, TypeEngine

_CROCKFORD = "0123456789ABCDEFGHJKMNPQRSTVWXYZ"
ENUM_LENGTH = 32
"""Every string enum is stored as ``VARCHAR(32)``, so adding a value never changes the column."""


BigIntId: TypeEngine[int] = BigInteger()
"""The type of every integer primary key (and so of the foreign keys that point at one): ``BIGINT``.

A ``SERIAL`` is 32-bit, and high-volume tables (``run_events``, ``audit_log``,
``webhook_deliveries``) burn ids that are never reused, while the web layer accepts any id up to
2**63 - 1 (a larger one in a URL must be a 404, not an int4 overflow). Migration 0009 widened the
columns.
"""


def new_id(prefix: str) -> str:
    """Return ``<prefix>_<ULID>``: 48-bit millisecond time + 80 random bits, Crockford base32.

    Ids sort by creation time (lexicographically, within one prefix) and are safe in URLs.
    """
    value = (time.time_ns() // 1_000_000) << 80 | int.from_bytes(os.urandom(10), "big")
    chars = []
    for _ in range(26):
        value, digit = divmod(value, 32)
        chars.append(_CROCKFORD[digit])
    return f"{prefix}_{''.join(reversed(chars))}"


def utc_now() -> datetime:
    """Aware UTC now; the default for ``created_at``-style columns."""
    return datetime.now(UTC)


def str_enum(literal: Any) -> Enum:
    """A non-native string enum over the values of a ``Literal[...]`` alias.

    Values are validated in Python on bind (``validate_strings``); no CHECK constraint is emitted so
    that adding a value is a model change only.
    """
    values = get_args(literal)
    if not values or not all(isinstance(v, str) for v in values):
        raise TypeError(f"str_enum needs a Literal of strings, got {literal!r}")
    return Enum(
        *values,
        native_enum=False,
        create_constraint=False,
        validate_strings=True,
        length=ENUM_LENGTH,
    )


class UTCDateTime(TypeDecorator[datetime]):
    """A timezone-aware UTC datetime (``timestamptz``): naive datetimes are rejected on bind, and
    every value is converted to UTC on the way in and out."""

    impl = DateTime(timezone=True)
    cache_ok = True

    def process_bind_param(self, value: datetime | None, dialect: Dialect) -> datetime | None:
        if value is None:
            return None
        if value.tzinfo is None:
            raise ValueError(f"naive datetime {value!r}: coverset stores aware UTC datetimes only")
        return value.astimezone(UTC)

    def process_result_value(self, value: datetime | None, dialect: Dialect) -> datetime | None:
        if value is None:
            return None
        if value.tzinfo is None:
            return value.replace(tzinfo=UTC)
        return value.astimezone(UTC)
