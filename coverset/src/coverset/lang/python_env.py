"""Where a Python repository's test environment comes from, and how the project itself gets installed.

:class:`~coverset.lang.python.PythonAdapter` turns a checkout into an
:class:`~coverset.lang.base.EnvSpec`: a pinned ``requirements.txt`` of third-party packages, a Python
version and the way the project is installed. Most repositories are not uv-locked, so the
requirements come from the first source that applies, in this order:

========================  ==================================================================  ===========
``env_source``            Read from                                                           Pinned by
========================  ==================================================================  ===========
``uv.lock``               ``uv.lock`` (``uv export --frozen --offline``)                      the lock
``requirements``          ``[tool.coverset] requirements``, else ``requirements*.txt`` and    ``uv pip compile``
                          ``requirements/*.txt`` that look like runtime/test/dev files, plus
                          the project's own declared dependencies
``poetry``                ``poetry.lock``, converted here (no Poetry needed)                  the lock
``pipenv``                ``Pipfile.lock``, converted here                                    the lock
``pyproject``             ``[project]`` dependencies, every extra, the ``test``/``dev``        ``uv pip compile``
                          dependency groups
``setup``                 ``setup.cfg`` ``[options]`` or ``setup.py`` keyword literals         ``uv pip compile``
========================  ==================================================================  ===========

An explicit ``[tool.coverset] requirements`` wins over every lock.

**Nothing from the repository runs on the control plane.** The environment is described for every
pull request, untrusted ones included, on the machine that holds the forge credentials, so this module
never executes repository code: ``setup.py`` is read with :mod:`ast` (keyword arguments that are
literals, or names bound to literals), ``setup.cfg`` with :mod:`configparser`, locks with
:mod:`tomllib` and :mod:`json`; the project itself is never handed to a resolver (its own entry is
dropped from every input, as ``uv export --no-emit-project`` does), so no build backend runs; and
``uv pip compile`` runs with ``--no-build``, so a dependency that ships only an sdist fails to
resolve instead of running its ``setup.py`` here. Index options in requirement files (``--index-url``,
``--extra-index-url``, ``--find-links``, ``--trusted-host``) are dropped: a pull request must not
choose where the control plane downloads from. The operator's ``UV_INDEX_URL``,
``UV_EXTRA_INDEX_URL``, ``UV_DEFAULT_INDEX`` and ``UV_INDEX`` are passed to ``uv`` for private
indexes. For the same reason the resolver never sees a direct reference: ``name @ url`` and bare
VCS/URL lines (from requirement files, project metadata or a lock) are split out before
``uv pip compile`` and appended verbatim after the compiled pins, so their own dependencies are
resolved only when a trusted build installs the environment, and
:func:`~coverset.executors.env_export.direct_references` keeps them out of untrusted builds
altogether. ``file:`` URLs (``git+file://`` included) and filesystem paths are refused wherever they
appear: they would make the builder read a directory outside the checkout. Packages that live in the
repository are relative paths, handled as :class:`LocalPackage` entries.

**Determinism.** ``uv pip compile`` resolves against the live index, so the same inputs could pin
different versions tomorrow. Each compile is cached by the sha256 of what was resolved (the
normalised requirement lines, constraints, Python version and resolver options) under
``<cache>/requirements/<key>.txt``, which makes the result, and therefore ``env_hash``, a function of
the inputs. The compile runs offline first against coverset's own uv cache (``<cache>/uv-cache``) and
goes online only when that fails, so after the first resolution of a set of inputs no network is
needed. ``--universal`` gives one resolution with markers that installs on the macOS control plane
(LocalExecutor) and in Linux sandboxes (Modal) alike. The emitted text starts with a header naming
the source, the inputs and the digest of the compile input, so ``env_hash`` changes exactly when the
resolved inputs do (a comment edited in ``requirements.txt`` does not rebuild anything).

**Installing the project.** coverset normally never installs the project: tests import it through
``PYTHONPATH=<source_root>``, which keeps a PR's pure-Python changes visible without any build.
Some projects only work installed: plugins registered as entry points, a package that reads its own
version with :mod:`importlib.metadata` at import time, a version file generated by setuptools-scm or
hatch-vcs, compiled extension modules. :func:`resolve_install` turns ``[tool.coverset] install``
(``auto``, ``none``, ``editable``, ``wheel``) into an :class:`InstallPlan`; for anything but ``none``
the build backend's ``[build-system] requires`` join the environment so the project can be built
without network and without build isolation inside a sandbox. The executors install at trusted-
snapshot time (Modal: a default-branch commit, before the snapshot is taken) or per commit into a
side directory (LocalExecutor), always with ``--no-deps``. ``PYTHONPATH`` still comes first, so the
installed copy only supplies what the source tree cannot: distribution metadata (entry points,
``version()``), and, through the small import hook written by :data:`FALLBACK_WRITER`, compiled
extension modules and files the build generated. A PR that changes C sources therefore runs against
the default branch's build until the next snapshot; ``coverset doctor`` says so.
"""

