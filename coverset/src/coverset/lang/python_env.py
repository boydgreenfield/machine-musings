@dataclass(frozen=True, slots=True)
class LocalPackage:
    """A package that lives in the repository (a committed wheel, a path dependency, a workspace member).

    Locks reference these by path, which means nothing inside a worker, so the requirements never
    carry them (``uv export --no-emit-local``). They are recorded as ``# coverset-local:`` comment
    lines instead, which keeps them in ``env_hash``, and installed with ``--no-deps`` from the
    worker's checkout together with the project (:func:`install_needed`).
    """

    kind: Literal["file", "dir", "editable"]
    path: str
    name: str
    marker: str | None = None

    def line(self) -> str:
        """The ``# coverset-local:`` comment line that records this package in the requirements."""
        return f"{LOCAL_PREFIX} {self.kind} {self.path} {self.name}" + (
            f" ; {self.marker}" if self.marker else ""
        )

    def requirement(self, repo_dir: str) -> str:
        """A pip/uv requirement installing this package from ``repo_dir`` (markers kept)."""
        url = Path(repo_dir, self.path).as_uri()
        return f"{self.name} @ {url}" + (f" ; {self.marker}" if self.marker else "")


LOCAL_PREFIX: Final = "# coverset-local:"
_LOCAL_RE: Final = re.compile(
    r"^# coverset-local: (file|dir|editable) (\S+) ([A-Za-z0-9][A-Za-z0-9._-]*)(?: ; (.+))?$"
)


def local_packages(requirements_txt: str) -> list[LocalPackage]:
    """The :class:`LocalPackage` lines recorded in an environment's requirements (validated again)."""
    found = []
    for line in requirements_txt.splitlines():
        match = _LOCAL_RE.match(line.strip())
        if match is None:
            continue
        kind, path, name, marker = match.groups()
        try:
            path = rel_path(path, "local package")
            marker = str(Marker(marker)) if marker else None
        except (ConfigError, InvalidMarker):
            continue
        found.append(LocalPackage(kind, path, name, marker))  # type: ignore[arg-type]
    return found


def install_needed(spec: Any) -> bool:
    """Whether an environment needs the install step: the project itself, or local packages."""
    return getattr(spec, "install", "none") != "none" or LOCAL_PREFIX in getattr(spec, "requirements_txt", "")


def _safe_exists(repo_root: Path, rel: str) -> Literal["file", "dir"] | None:
    """``file``/``dir`` when ``rel`` exists in the checkout without going through a symlink, else None."""
    try:
        rel = rel_path(rel, "path")
    except ConfigError:
        return None
    current = repo_root
    for part in PurePosixPath(rel).parts:
        current = current / part
        try:
            info = current.lstat()
        except OSError:
            return None
        if stat.S_ISLNK(info.st_mode):
            return None
    return "dir" if stat.S_ISDIR(info.st_mode) else "file" if stat.S_ISREG(info.st_mode) else None


def _local_name(repo_root: Path, rel: str, kind: str) -> str | None:
    """A local package's distribution name: from a wheel/sdist file name, else its own metadata."""
    if kind == "file":
        name = PurePosixPath(rel).name
        match = re.match(r"^([A-Za-z0-9][A-Za-z0-9._]*?)-\d", name)
        return match.group(1) if match else None
    try:
        meta = project_metadata(repo_root / rel)
    except (ConfigError, OSError):
        return None
    return meta.name if meta.name and re.fullmatch(r"[A-Za-z0-9][A-Za-z0-9._-]*", meta.name) else None


def _local_build_requires(repo_root: Path, packages: Sequence[LocalPackage]) -> list[str]:
    """``[build-system] requires`` of local directory packages (they are built without isolation)."""
    out: list[str] = []
    for package in packages:
        if package.kind == "file":
            continue
        try:
            text = read_repo_text(repo_root, f"{package.path}/pyproject.toml", MAX_PYPROJECT_BYTES)
            doc = tomllib.loads(text) if text else {}
        except (ConfigError, tomllib.TOMLDecodeError):
            continue
        build = doc.get("build-system") if isinstance(doc.get("build-system"), dict) else None
        requires = _strings(build.get("requires")) if build else list(DEFAULT_BUILD_REQUIRES)
        out += [r for r in requires if _clean_requirement(r) is not None and r not in out]
    return out


_LOCAL_SOURCE_RE: Final = re.compile(r'source = \{ (?:path|directory) = |source = \{ editable = "(?!\.")')


def uv_lock_local_packages(lock_text: str) -> tuple[list[LocalPackage], list[str]]:
    """Path, directory and editable (non-root) packages of a ``uv.lock``, with their markers.

    Most locks have none, and parsing a large lock costs ~100 ms, so a substring check comes first.
    """
    if not _LOCAL_SOURCE_RE.search(lock_text):
        return [], []
    try:
        doc = tomllib.loads(lock_text)
    except tomllib.TOMLDecodeError as exc:
        raise ConfigError(f"uv.lock does not parse: {exc}") from exc
    packages = [p for p in doc.get("package", []) if isinstance(p, dict)]
    edges: dict[tuple[str, str], list[str | None]] = {}
    for package in packages:
        for table in ("dependencies", "dev-dependencies", "optional-dependencies"):
            entries = package.get(table)
            groups = entries.values() if isinstance(entries, dict) else [entries]
            for group in groups:
                for dep in group if isinstance(group, list) else []:
                    if isinstance(dep, dict) and isinstance(dep.get("name"), str):
                        source = json.dumps(dep.get("source"), sort_keys=True) if dep.get("source") else ""
                        marker = dep["marker"] if isinstance(dep.get("marker"), str) else None
                        edges.setdefault((normalise(dep["name"]), source), []).append(marker)
    found: list[LocalPackage] = []
    notes: list[str] = []
    for package in packages:
        source = package.get("source") if isinstance(package.get("source"), dict) else {}
        name = package.get("name")
        if not isinstance(name, str):
            continue
        if "path" in source:
            path, kind = (
                source["path"],
                ("dir" if not str(source["path"]).endswith((".whl", ".tar.gz", ".zip")) else "file"),
            )
        elif "directory" in source:
            path, kind = source["directory"], "dir"
        elif "editable" in source and source["editable"] not in (".", ""):
            path, kind = source["editable"], "editable"
        else:
            continue
        key = json.dumps(source, sort_keys=True)
        markers = edges.get((normalise(name), key), []) + edges.get((normalise(name), ""), [])
        marker = None
        if markers and all(m is not None for m in markers):
            unique = sorted({m for m in markers if m})
            marker = unique[0] if len(unique) == 1 else " or ".join(f"({m})" for m in unique)
        elif not markers:
            notes.append(f"uv.lock: local package {shown(name)} is not a dependency of anything, skipped")
            continue
        found.append(_checked_local(kind, str(path), name, marker, notes))
    return [f for f in found if f is not None], notes


def _checked_local(
    kind: str, path: str, name: str, marker: str | None, notes: list[str]
) -> LocalPackage | None:
    try:
        path = rel_path(path, "local package")
        marker = str(Marker(marker)) if marker else None
    except (ConfigError, InvalidMarker):
        notes.append(f"local package {shown(name)} has an unusable path or marker, skipped")
        return None
    if any(ch.isspace() for ch in path) or not re.fullmatch(r"[A-Za-z0-9][A-Za-z0-9._-]*", name):
        notes.append(f"local package {shown(name)} has an unusable path or name, skipped")
        return None
    return LocalPackage(kind, path, name, marker)  # type: ignore[arg-type]


@dataclass(slots=True)
class RequirementsInput:
    """What a set of requirement files (and project metadata) contribute to a resolution."""

    requirements: list[str] = field(default_factory=list)
    constraints: list[str] = field(default_factory=list)
    files: list[str] = field(default_factory=list)
    """Every repo-relative file read, includes and constraints included, in reading order."""
    notes: list[str] = field(default_factory=list)
    """What was dropped or adjusted, for the doctor (``-e .`` dropped, index options ignored...)."""
    local: list[LocalPackage] = field(default_factory=list)
    """Wheels and directories in the repository the files reference (installed with the project)."""

    def add_requirement(self, line: str, origin: str) -> None:
        """Keep ``line`` if it is a requirement or an acceptable direct URL; otherwise note the drop.

        Direct references stay in :attr:`requirements` (they are part of the environment) but are
        never resolved here: :func:`resolve_environment` splits them out before ``uv pip compile``.
        """
        refused = _refused_reference(line)
        if refused is not None:
            self.notes.append(f"{origin}: refused {shown(line)}: {refused}")
            return
        cleaned = _clean_requirement(line)
        if cleaned is None:
            self.notes.append(f"{origin}: ignored {shown(line)} (not a requirement)")
        elif cleaned not in self.requirements:
            self.requirements.append(cleaned)


def _clean_requirement(line: str) -> str | None:
    """``line`` as one safe requirement line, or None.

    A PEP 508 requirement is re-rendered by :mod:`packaging` (so nothing that reaches ``uv`` can be an
    option); a bare VCS/HTTP URL without whitespace is kept as it is. Direct references the control
    plane must never accept (:func:`_refused_reference`: ``file:`` URLs, filesystem paths, unknown
    schemes) give None.
    """
    text = line.strip()
    if not text or text.startswith(("-", "@", "#")) or _refused_reference(text) is not None:
        return None
    if text.startswith(_VCS_PREFIXES):
        return text if not any(ch.isspace() for ch in text) else None
    try:
        return str(Requirement(text))
    except InvalidRequirement:
        return None


def direct_url(line: str) -> str | None:
    """The URL (or path) of a direct reference, ``name @ url`` or a bare VCS/URL line, else None."""
    text = line.strip()
    if text.startswith(_VCS_PREFIXES):
        return text.split()[0] if text.split() else None
    if "@" not in text:
        return None
    try:
        return Requirement(text).url
    except InvalidRequirement:
        return None


def _refused_reference(line: str) -> str | None:
    """Why the direct reference in ``line`` is refused outright, or None (no reference, or acceptable).

    Only network URLs (``http``/``https``, and ``ssh``/``git`` behind a VCS prefix) are kept. A
    ``file:`` URL (``git+file://`` included) or a bare filesystem path would make whoever builds the
    environment read a directory outside the checkout: on the control plane that is a local file
    disclosure chosen by a pull request. Packages that live in the repository are expressed as
    relative paths and handled as :class:`LocalPackage` entries instead.
    """
    url = direct_url(line)
    if url is None:
        return None
    scheme, sep, _ = url.partition("://")
    if not sep:
        return "a filesystem path is not a URL (repository packages are given as relative paths)"
    base = scheme.lower().rpartition("+")[2]
    if base not in _DIRECT_URL_SCHEMES:
        return f"{shown(base)} URLs are refused (only http, https, ssh and git)"
    return None


def split_direct(requirements: Sequence[str]) -> tuple[list[str], list[str]]:
    """``requirements`` split into (index requirements by name, direct references) in order."""
    named: list[str] = []
    direct: list[str] = []
    for line in requirements:
        (direct if direct_url(line) is not None else named).append(line)
    return named, direct


def _logical_lines(text: str) -> Iterator[str]:
    """Lines of a pip requirements file with ``\\``-continuations joined and comments removed."""
    pending = ""
    for raw in text.splitlines():
        if raw.endswith("\\"):
            pending += raw[:-1] + " "
            continue
        line = pending + raw
        pending = ""
        if line.lstrip().startswith("#"):
            continue
        line = re.sub(r"(^|\s)#.*$", "", line).strip()
        if line:
            yield line
    if pending.strip():
        yield pending.strip()


def read_requirement_files(
    repo_root: Path, files: Sequence[str], *, into: RequirementsInput | None = None
) -> RequirementsInput:
    """Parse pip requirement files with their ``-r``/``-c`` includes resolved inside the repository.

    ``-e .``, ``-e <path>`` and plain local paths are dropped (the project is installed by
    ``[tool.coverset] install``, never from a requirements file); index and build options are dropped;
    per-requirement ``--hash`` options are removed (the result is re-pinned anyway). A missing
    configured file is a ConfigError; a missing include is noted.
    """
    result = into if into is not None else RequirementsInput()
    seen: set[str] = set(result.files)
    for rel in files:
        _read_one(repo_root, rel_path(rel, "requirements"), result, seen, constraint=False, required=True)
    return result


def _read_one(
    repo_root: Path,
    rel: str,
    result: RequirementsInput,
    seen: set[str],
    *,
    constraint: bool,
    required: bool,
) -> None:
    if rel in seen:
        return
    if len(seen) >= MAX_REQUIREMENT_FILES:
        raise ConfigError(f"more than {MAX_REQUIREMENT_FILES} requirement files (includes counted)")
    seen.add(rel)
    text = read_repo_text(repo_root, rel, MAX_REQUIREMENTS_BYTES)
    if text is None:
        if required:
            raise ConfigError(f"requirements file {shown(rel)} does not exist")
        result.notes.append(f"{rel}: not found (included by another file), skipped")
        return
    result.files.append(rel)
    base = PurePosixPath(rel).parent
    for line in _logical_lines(text):
        words = line.split()
        head = words[0]
        if head.startswith("--"):
            option, _, attached = head.partition("=")
            value = attached or (words[1] if len(words) > 1 else "")
        elif head.startswith("-"):
            option, attached = head[:2], head[2:].lstrip("=")
            value = attached or (words[1] if len(words) > 1 else "")
        else:
            option = value = ""
        if option in ("-r", "--requirement", "-c", "--constraint"):
            include = _include_path(base, value)
            if include is None:
                result.notes.append(f"{rel}: include {shown(value)} leaves the repository, skipped")
                continue
            nested = constraint or option in ("-c", "--constraint")
            _read_one(repo_root, include, result, seen, constraint=nested, required=False)
        elif option in ("-e", "--editable"):
            if value.startswith(_VCS_PREFIXES[:4]):
                result.add_requirement(value, rel)
                result.notes.append(f"{rel}: editable {shown(value)} installed as a regular requirement")
            else:
                _local_from_file(repo_root, base, value, rel, result, editable=True)
        elif option:
            kind = "index option" if option.startswith(_INDEX_OPTIONS) else "option"
            result.notes.append(
                f"{rel}: {kind} {shown(option)} ignored (indexes are set on the control plane)"
            )
        elif head in (".", "..") or head.startswith(("./", "../", "/", "file:")) or head.endswith(".whl"):
            _local_from_file(repo_root, base, line, rel, result, editable=False)
        else:
            requirement = re.sub(
                r"\s--(?:hash|global-option|config-settings)[=\s]\S+", "", " " + line
            ).strip()
            if constraint:
                cleaned = _clean_requirement(requirement)
                if cleaned is not None and direct_url(cleaned) is not None:
                    # a constraint is handed to the resolver, which would fetch the URL
                    result.notes.append(
                        f"{rel}: constraint {shown(requirement)} is a direct reference, ignored"
                    )
                elif cleaned is not None and cleaned not in result.constraints:
                    result.constraints.append(cleaned)
            else:
                result.add_requirement(requirement, rel)


def _local_from_file(
    repo_root: Path, base: PurePosixPath, text: str, origin: str, result: RequirementsInput, *, editable: bool
) -> None:
    """Record a local path from a requirements file as a :class:`LocalPackage` (or note why not)."""
    target, _, marker = text.partition(" ;")
    target = target.strip().removeprefix("file:").removeprefix("//")
    path = _include_path(base, target) if not target.startswith("/") else None
    if path is None:
        if target.strip("./") == "":  # ".", "./", "..", "../" from a subdirectory: the repository root
            result.notes.append(
                f"{origin}: {'editable ' if editable else ''}install of the project itself dropped "
                "(it is installed per [tool.coverset] install)"
            )
        else:
            result.notes.append(f"{origin}: local path {shown(target)} is outside the repository, skipped")
        return
    found = _safe_exists(repo_root, path)
    if found is None:
        result.notes.append(f"{origin}: local path {shown(path)} does not exist in the repository, skipped")
        return
    kind = "editable" if editable and found == "dir" else found
    name = _local_name(repo_root, path, kind if kind == "file" else "dir")
    if name is None:
        result.notes.append(f"{origin}: cannot tell the package name of {shown(path)}, skipped")
        return
    package = _checked_local(kind, path, name, marker.strip() or None, result.notes)
    if package is not None and package not in result.local:
        result.local.append(package)
        result.notes.append(f"{origin}: local package {name} ({path}) is installed from the checkout")


def _include_path(base: PurePosixPath, target: str) -> str | None:
    """``target`` relative to the including file's directory, or None when it leaves the repository."""
    if not target or target.startswith(("/", "\\")) or "://" in target or "\0" in target:
        return None
    parts: list[str] = []
    for part in (*base.parts, *PurePosixPath(target).parts):
        if part in ("", "."):
            continue
        if part == "..":
            if not parts:
                return None
            parts.pop()
        else:
            parts.append(part)
    return "/".join(parts) if parts else None


def auto_requirement_files(repo_root: Path) -> list[str]:
    """Requirement files coverset picks up when ``[tool.coverset] requirements`` is not set.

    ``*requirements*.txt`` at the top and ``requirements/*.txt`` (also ``reqs/``), keeping files whose
    name says runtime (``requirements.txt``, ``base``, ``main``, ``prod``...) or tests/development
    (``test``, ``tests``, ``testing``, ``dev``...), and skipping minimum-version, docs and lock-style
    variants (``tests-min.txt`` pins the oldest supported versions and conflicts with ``tests.txt``).
    Only ``.txt``: pip-tools ``.in`` sources are what the ``.txt`` beside them was compiled from.
    """
    candidates: list[str] = []
    try:
        top = sorted(
            p.name for p in repo_root.iterdir() if p.name.endswith(".txt") and "requirements" in p.name
        )
    except OSError:
        top = []
    candidates += top
    for folder in ("requirements", "reqs"):
        path = repo_root / folder
        if path.is_dir() and not path.is_symlink():
            candidates += sorted(f"{folder}/{p.name}" for p in path.iterdir() if p.name.endswith(".txt"))
    chosen = []
    for rel in candidates:
        if not (repo_root / rel).is_file() or (repo_root / rel).is_symlink():
            continue
        tokens = {t for t in _TOKEN_RE.split(PurePosixPath(rel).stem.lower()) if t}
        if tokens & (TEST_GROUPS | _RUNTIME_TOKENS) and not tokens & _SKIP_TOKENS:
            chosen.append(rel)
    return chosen


# -- project metadata -------------------------------------------------------------------------------------


@dataclass(slots=True)
class ProjectMetadata:
    """The project's own declared dependencies and packaging facts, read without running anything."""

    origin: str = ""
    """``pyproject``, ``setup.cfg`` or ``setup.py``; empty when no metadata was found."""
    name: str | None = None
    dependencies: list[str] = field(default_factory=list)
    extras: dict[str, list[str]] = field(default_factory=dict)
    groups: dict[str, list[str]] = field(default_factory=dict)
    """Test/dev dependency groups only (PEP 735, legacy ``tool.uv.dev-dependencies``, ``tests_require``)."""
    files: list[str] = field(default_factory=list)
    notes: list[str] = field(default_factory=list)
    dynamic_unresolved: bool = False
    """The dependencies are computed by code (a dynamic ``setup.py``) and could not be read."""
    entry_point_groups: list[str] = field(default_factory=list)
    """Entry-point groups other than console/gui scripts (plugins visible only when installed)."""
    scripts: list[str] = field(default_factory=list)
    ext_modules: bool = False
    requires_python: str | None = None
    py_modules: list[str] = field(default_factory=list)
    packages: list[str] = field(default_factory=list)
    """Packages the build configuration names explicitly (top-level names)."""
    package_dir: str | None = None
    """The directory the build configuration maps the root package namespace to (``src``)."""

    def all_requirements(self) -> list[str]:
        """Dependencies, then every extra, then the test/dev groups, the project itself removed."""
        out: list[str] = []
        own = normalise(self.name) if self.name else None
        for line in [*self.dependencies, *_flatten(self.extras.values()), *_flatten(self.groups.values())]:
            refused = _refused_reference(line)
            if refused is not None:
                self.notes.append(f"{self.origin}: refused {shown(line)}: {refused}")
                continue
            cleaned = _clean_requirement(line)
            if cleaned is None:
                self.notes.append(f"{self.origin}: ignored {shown(line)} (not a requirement)")
                continue
            if (
                own is not None
                and not cleaned.startswith(_VCS_PREFIXES)
                and normalise(Requirement(cleaned).name) == own
            ):
                continue  # "pkg[test]" inside pkg's own extras: every extra is installed anyway
            if cleaned not in out:
                out.append(cleaned)
        return out


def _flatten(lists: Iterable[list[str]]) -> list[str]:
    return [item for items in lists for item in items]


def _strings(value: object) -> list[str]:
    if isinstance(value, str):
        return [
            line.strip() for line in value.splitlines() if line.strip() and not line.strip().startswith("#")
        ]
    if isinstance(value, list | tuple):
        return [v for v in value if isinstance(v, str)]
    return []


def project_metadata(repo_root: Path, pyproject: Mapping[str, Any] | None = None) -> ProjectMetadata:
    """The project's metadata from ``[project]``, else ``setup.cfg``, else ``setup.py`` (by AST).

    ``[project]`` is used when it names dependencies statically or through setuptools'
    ``[tool.setuptools.dynamic]`` file references; packaging facts (entry points, extension modules,
    packages) are gathered from every file present.
    """
    doc = pyproject if pyproject is not None else load_pyproject(repo_root)
    meta = ProjectMetadata()
    project = doc.get("project") if isinstance(doc.get("project"), dict) else None
    tool = doc.get("tool") if isinstance(doc.get("tool"), dict) else {}
    setup_cfg = _setup_cfg(repo_root)
    setup_py = _setup_py(repo_root)
    if project is not None:
        meta.origin = "pyproject"
        meta.files.append("pyproject.toml")
        meta.name = project.get("name") if isinstance(project.get("name"), str) else None
        dynamic = set(_strings(project.get("dynamic")))
        meta.dependencies = _strings(project.get("dependencies"))
        extras = project.get("optional-dependencies")
        if isinstance(extras, dict):
            meta.extras = {str(k): _strings(v) for k, v in extras.items()}
        setuptools_dynamic = (
            tool.get("setuptools", {}).get("dynamic", {}) if isinstance(tool.get("setuptools"), dict) else {}
        )
        if "dependencies" in dynamic:
            files = _dynamic_files(setuptools_dynamic.get("dependencies"))
            if files:
                read = read_requirement_files(repo_root, files)
                meta.dependencies = read.requirements
                meta.files += read.files
                meta.notes += read.notes
            elif setup_cfg is not None and setup_cfg.dependencies:
                meta.dependencies = setup_cfg.dependencies
                meta.files.append("setup.cfg")
            elif setup_py is not None and setup_py.dependencies:
                meta.dependencies = setup_py.dependencies
                meta.files.append("setup.py")
            else:
                meta.dynamic_unresolved = True
                meta.notes.append("pyproject.toml: dependencies are dynamic and not read from a file")
        if "optional-dependencies" in dynamic and isinstance(setuptools_dynamic, dict):
            optional = setuptools_dynamic.get("optional-dependencies")
            if isinstance(optional, dict):
                for extra, spec in optional.items():
                    files = _dynamic_files(spec)
                    if files:
                        read = read_requirement_files(repo_root, files)
                        meta.extras[str(extra)] = read.requirements
                        meta.files += read.files
        meta.groups = _dependency_groups(doc)
        meta.requires_python = (
            project.get("requires-python") if isinstance(project.get("requires-python"), str) else None
        )
        entry_points = project.get("entry-points")
        if isinstance(entry_points, dict):
            meta.entry_point_groups = sorted(str(g) for g in entry_points)
        meta.scripts = sorted(
            str(name)
            for table in ("scripts", "gui-scripts")
            if isinstance(project.get(table), dict)
            for name in project[table]
        )
    elif setup_cfg is not None and (setup_cfg.dependencies or setup_cfg.name or setup_cfg.extras):
        meta = setup_cfg
    elif setup_py is not None:
        meta = setup_py
    poetry = tool.get("poetry") if isinstance(tool.get("poetry"), dict) else None
    if poetry is not None:
        meta.name = meta.name or (poetry.get("name") if isinstance(poetry.get("name"), str) else None)
        plugins = poetry.get("plugins")
        if isinstance(plugins, dict):
            meta.entry_point_groups = sorted({*meta.entry_point_groups, *map(str, plugins)})
        if isinstance(poetry.get("scripts"), dict):
            meta.scripts = sorted({*meta.scripts, *map(str, poetry["scripts"])})
        meta.packages = sorted({*meta.packages, *_poetry_packages(poetry)})
        if meta.package_dir is None:
            meta.package_dir = _poetry_package_dir(poetry)
    for other in (setup_cfg, setup_py):
        if other is None or other is meta:
            continue
        meta.entry_point_groups = sorted({*meta.entry_point_groups, *other.entry_point_groups})
        meta.ext_modules = meta.ext_modules or other.ext_modules
        meta.packages = sorted({*meta.packages, *other.packages})
        meta.py_modules = sorted({*meta.py_modules, *other.py_modules})
        meta.package_dir = meta.package_dir or other.package_dir
        meta.requires_python = meta.requires_python or other.requires_python
        meta.name = meta.name or other.name
    _tool_layout(tool, meta)
    return meta


def _dynamic_files(spec: object) -> list[str]:
    if isinstance(spec, dict):
        return _strings(spec.get("file"))
    return []


def _dependency_groups(doc: Mapping[str, Any]) -> dict[str, list[str]]:
    """Test/dev groups from PEP 735 ``[dependency-groups]`` (``include-group`` resolved) and uv's legacy
    ``dev-dependencies``."""
    groups = doc.get("dependency-groups")
    found: dict[str, list[str]] = {}
    if isinstance(groups, dict):
        by_name = {normalise(str(k)): v for k, v in groups.items()}

        def expand(name: str, depth: int = 0) -> list[str]:
            if depth > 16:
                return []
            out: list[str] = []
            entries = by_name.get(name, [])
            for entry in entries if isinstance(entries, list) else []:
                if isinstance(entry, str):
                    out.append(entry)
                elif isinstance(entry, dict) and isinstance(entry.get("include-group"), str):
                    out += expand(normalise(entry["include-group"]), depth + 1)
            return out

        for name in by_name:
            if name in TEST_GROUPS:
                found[name] = expand(name)
    tool = doc.get("tool") if isinstance(doc.get("tool"), dict) else {}
    uv = tool.get("uv") if isinstance(tool.get("uv"), dict) else {}
    legacy = _strings(uv.get("dev-dependencies"))
    if legacy:
        found.setdefault("dev", []).extend(legacy)
    return found


def _poetry_packages(poetry: Mapping[str, Any]) -> list[str]:
    packages = poetry.get("packages")
    names = []
    for entry in packages if isinstance(packages, list) else []:
        if isinstance(entry, dict) and isinstance(entry.get("include"), str):
            names.append(entry["include"].split("/")[0].removesuffix(".py"))
    return names


def _poetry_package_dir(poetry: Mapping[str, Any]) -> str | None:
    packages = poetry.get("packages")
    for entry in packages if isinstance(packages, list) else []:
        if isinstance(entry, dict) and isinstance(entry.get("from"), str):
            return entry["from"]
    return None


def _tool_layout(tool: Mapping[str, Any], meta: ProjectMetadata) -> None:
    """Explicit packages and package directories from setuptools and hatch configuration."""
    setuptools = tool.get("setuptools") if isinstance(tool.get("setuptools"), dict) else {}
    if setuptools:
        if setuptools.get("ext-modules"):
            meta.ext_modules = True
        packages = setuptools.get("packages")
        if isinstance(packages, list):
            meta.packages = sorted(
                {*meta.packages, *(p.split(".")[0] for p in packages if isinstance(p, str))}
            )
        elif isinstance(packages, dict) and isinstance(packages.get("find"), dict):
            where = _strings(packages["find"].get("where"))
            if where and meta.package_dir is None:
                meta.package_dir = where[0]
        package_dir = setuptools.get("package-dir")
        if (
            isinstance(package_dir, dict)
            and isinstance(package_dir.get(""), str)
            and meta.package_dir is None
        ):
            meta.package_dir = package_dir[""]
        meta.py_modules = sorted({*meta.py_modules, *_strings(setuptools.get("py-modules"))})
    hatch = tool.get("hatch") if isinstance(tool.get("hatch"), dict) else {}
    wheel = (
        hatch.get("build", {}).get("targets", {}).get("wheel", {})
        if isinstance(hatch.get("build"), dict)
        else {}
    )
    if isinstance(wheel, dict):
        for entry in _strings(wheel.get("packages")):
            path = PurePosixPath(entry)
            meta.packages = sorted({*meta.packages, path.name})
            if len(path.parts) > 1 and meta.package_dir is None:
                meta.package_dir = str(path.parent)


def _setup_cfg(repo_root: Path) -> ProjectMetadata | None:
    text = read_repo_text(repo_root, "setup.cfg", MAX_SETUP_BYTES)
    if text is None:
        return None
    parser = configparser.ConfigParser(interpolation=None, strict=False)
    try:
        parser.read_string(text)
    except configparser.Error as exc:
        raise ConfigError(f"setup.cfg does not parse: {str(exc)[:200]}") from exc
    meta = ProjectMetadata(origin="setup.cfg", files=["setup.cfg"])
    meta.name = parser.get("metadata", "name", fallback=None)
    install = parser.get("options", "install_requires", fallback="")
    if install.strip().startswith("file:"):
        files = install.strip()[5:].replace(",", " ").split()
        read = read_requirement_files(repo_root, files)
        meta.dependencies, meta.files = read.requirements, [*meta.files, *read.files]
    else:
        meta.dependencies = _strings(install)
    tests = _strings(parser.get("options", "tests_require", fallback=""))
    if tests:
        meta.groups["tests_require"] = tests
    if parser.has_section("options.extras_require"):
        meta.extras = {k: _strings(v) for k, v in parser.items("options.extras_require")}
    if parser.has_section("options.entry_points"):
        meta.entry_point_groups = sorted(
            k for k, _ in parser.items("options.entry_points") if k not in ("console_scripts", "gui_scripts")
        )
        meta.scripts = _strings(parser.get("options.entry_points", "console_scripts", fallback=""))
    meta.requires_python = parser.get("options", "python_requires", fallback=None)
    package_dir = parser.get("options", "package_dir", fallback="")
    match = re.search(r"(?:^|\s)=\s*([A-Za-z0-9_./-]+)", package_dir)
    if match:
        meta.package_dir = match.group(1)
    meta.packages = sorted(
        {
            p.split(".")[0]
            for p in _strings(parser.get("options", "packages", fallback=""))
            if not p.startswith("find")
        }
    )
    meta.py_modules = _strings(parser.get("options", "py_modules", fallback=""))
    return meta


def _setup_py(repo_root: Path) -> ProjectMetadata | None:
    """Keyword arguments of ``setup(...)`` in ``setup.py`` that are literals (never executed)."""
    text = read_repo_text(repo_root, "setup.py", MAX_SETUP_BYTES)
    if text is None:
        return None
    meta = ProjectMetadata(origin="setup.py", files=["setup.py"])
    meta.ext_modules = bool(
        re.search(r"\bext_modules\b|\bExtension\(|\bcythonize\(|\bPybind11Extension\b", text)
    )
    try:
        tree = ast.parse(text)
    except (SyntaxError, ValueError, RecursionError, MemoryError):
        meta.dynamic_unresolved = True
        meta.notes.append("setup.py does not parse; its dependencies cannot be read")
        return meta
    assigned: dict[str, ast.expr] = {}
    for node in tree.body:
        if isinstance(node, ast.Assign) and len(node.targets) == 1 and isinstance(node.targets[0], ast.Name):
            assigned[node.targets[0].id] = node.value
    call = next(
        (
            node
            for node in ast.walk(tree)
            if isinstance(node, ast.Call)
            and (
                (isinstance(node.func, ast.Name) and node.func.id == "setup")
                or (isinstance(node.func, ast.Attribute) and node.func.attr == "setup")
            )
        ),
        None,
    )
    if call is None:
        meta.dynamic_unresolved = True
        meta.notes.append("setup.py has no setup(...) call coverset can read")
        return meta
    values: dict[str, object] = {}
    for keyword in call.keywords:
        if keyword.arg is None:
            continue
        node = keyword.value
        if isinstance(node, ast.Name) and node.id in assigned:
            node = assigned[node.id]
        try:
            values[keyword.arg] = ast.literal_eval(node)
        except (ValueError, TypeError, SyntaxError, RecursionError, MemoryError):
            values[keyword.arg] = _UNREADABLE
    for key in ("install_requires", "extras_require", "tests_require"):
        if values.get(key) is _UNREADABLE:
            meta.dynamic_unresolved = True
            meta.notes.append(f"setup.py computes {key}; coverset does not run setup.py")
    meta.name = values["name"] if isinstance(values.get("name"), str) else None
    meta.dependencies = _strings(values.get("install_requires"))
    extras = values.get("extras_require")
    if isinstance(extras, dict):
        meta.extras = {str(k): _strings(v) for k, v in extras.items()}
    tests = _strings(values.get("tests_require"))
    if tests:
        meta.groups["tests_require"] = tests
    entry_points = values.get("entry_points")
    if isinstance(entry_points, dict):
        meta.entry_point_groups = sorted(
            str(k) for k in entry_points if k not in ("console_scripts", "gui_scripts")
        )
        meta.scripts = _strings(entry_points.get("console_scripts"))
    elif entry_points is _UNREADABLE:
        meta.entry_point_groups = ["<computed in setup.py>"]
    if "ext_modules" in values:
        meta.ext_modules = True
    packages = values.get("packages")
    if isinstance(packages, list | tuple):
        meta.packages = sorted({str(p).split(".")[0] for p in packages if isinstance(p, str)})
    package_dir = values.get("package_dir")
    if isinstance(package_dir, dict) and isinstance(package_dir.get(""), str):
        meta.package_dir = package_dir[""]
    meta.py_modules = _strings(values.get("py_modules"))
    meta.requires_python = (
        values["python_requires"] if isinstance(values.get("python_requires"), str) else None
    )
    return meta


