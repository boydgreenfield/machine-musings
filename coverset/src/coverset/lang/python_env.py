# -- reading repository files safely -----------------------------------------------------------------


def shown(value: object) -> str:
    """A short, sanitised rendering of a repo-supplied value for error messages."""
    text = _SAFE_CHARS_RE.sub("?", str(value)[:20])
    return repr(text + ("..." if len(str(value)) > 20 else ""))


def rel_path(value: object, key: str) -> str:
    """A repo-relative POSIX path that does not escape the repo."""
    if not isinstance(value, str) or not value or "\0" in value or "\\" in value:
        raise ConfigError(f"{key} must be a relative path")
    path = PurePosixPath(value)
    if path.is_absolute() or ".." in path.parts:
        raise ConfigError(f"{key} must stay inside the repository: {shown(value)}")
    return str(path)


def open_regular(path: Path, *, no_follow: bool) -> BinaryIO:
    """Open ``path`` for reading; with ``no_follow`` refuse symlinks, FIFOs and devices.

    ``O_NONBLOCK`` keeps a FIFO from blocking the open; it is rejected right after by ``fstat``.
    Raises FileNotFoundError when the file does not exist.
    """
    if not no_follow:
        return path.open("rb")
    flags = os.O_RDONLY | getattr(os, "O_NOFOLLOW", 0) | getattr(os, "O_NONBLOCK", 0)
    try:
        fd = os.open(path, flags)
    except FileNotFoundError:
        raise
    except OSError as exc:  # ELOOP for a symlink under O_NOFOLLOW
        raise ConfigError(f"{path.name} must be a regular file in the repository") from exc
    if not stat.S_ISREG(os.fstat(fd).st_mode):
        os.close(fd)
        raise ConfigError(f"{path.name} must be a regular file in the repository")
    os.set_blocking(fd, True)
    return os.fdopen(fd, "rb")


def sha256_file(path: Path, *, max_bytes: int | None = None, no_follow: bool = False) -> str:
    """sha256 of ``path``; with ``no_follow`` it must be a regular file, not a symlink."""
    digest = hashlib.sha256()
    size = 0
    with open_regular(path, no_follow=no_follow) as fh:
        for chunk in iter(lambda: fh.read(1 << 20), b""):
            size += len(chunk)
            if max_bytes is not None and size > max_bytes:
                raise ConfigError(f"{path.name} is larger than {max_bytes} bytes")
            digest.update(chunk)
    return digest.hexdigest()


def read_repo_bytes(repo_root: Path, rel: str, max_bytes: int) -> bytes | None:
    """Bytes of the regular file ``rel`` (a repo-relative path), or None when it does not exist.

    No component of ``rel`` may be a symlink (a link to ``/`` inside the checkout must not let a
    configured path read the control plane's files); the file itself is opened with ``O_NOFOLLOW``.
    Files over ``max_bytes`` raise ConfigError.
    """
    rel = rel_path(rel, "path")
    parts = PurePosixPath(rel).parts
    current = repo_root
    for part in parts[:-1]:
        current = current / part
        try:
            info = current.lstat()
        except FileNotFoundError:
            return None
        if stat.S_ISLNK(info.st_mode) or not stat.S_ISDIR(info.st_mode):
            raise ConfigError(f"{shown(rel)} must not go through a symlink")
    try:
        fh = open_regular(repo_root.joinpath(*parts), no_follow=True)
    except FileNotFoundError:
        return None
    with fh:
        data = fh.read(max_bytes + 1)
    if len(data) > max_bytes:
        raise ConfigError(f"{PurePosixPath(rel).name} is larger than {max_bytes} bytes")
    return data


def read_repo_text(repo_root: Path, rel: str, max_bytes: int) -> str | None:
    """:func:`read_repo_bytes` decoded as UTF-8 (a BOM is dropped); ConfigError for other encodings."""
    data = read_repo_bytes(repo_root, rel, max_bytes)
    if data is None:
        return None
    try:
        return data.decode("utf-8-sig")
    except UnicodeDecodeError as exc:
        raise ConfigError(f"{PurePosixPath(rel).name} is not UTF-8 text") from exc


def load_pyproject(repo_root: Path) -> dict[str, Any]:
    """The parsed ``pyproject.toml`` of the checkout, ``{}`` when there is none."""
    text = read_repo_text(repo_root, "pyproject.toml", MAX_PYPROJECT_BYTES)
    if text is None:
        return {}
    try:
        return tomllib.loads(text)
    except tomllib.TOMLDecodeError as exc:
        raise ConfigError(f"pyproject.toml does not parse: {exc}") from exc


def normalise(name: str) -> str:
    """PEP 503 normalised distribution name."""
    return _NAME_RE.sub("-", name).lower()


