def poetry_lock_requirements(
    lock_text: str, pyproject: Mapping[str, Any] | None = None, *, own_name: str | None = None
) -> tuple[list[str], list[str], list[LocalPackage]]:
    """Pinned requirement lines (every group, every extra) from a ``poetry.lock``, notes, local packages.

    Lock format 2.1 (Poetry 2) carries each package's environment markers; older locks do not, so a
    package's marker is derived from the edges that lead to it (``[package.dependencies]`` entries and
    the root dependencies in ``pyproject``): when every edge has a marker, the package gets their
    disjunction (``pywin32`` only on Windows); one unconditional edge makes it unconditional. Directory
    and file sources become :class:`LocalPackage` entries (``develop = true``: editable), VCS and URL
    sources ``name @ url`` direct references, and packages from a named (private) source are pinned
    by name with a note.
    """
    try:
        doc = tomllib.loads(lock_text)
    except tomllib.TOMLDecodeError as exc:
        raise ConfigError(f"poetry.lock does not parse: {exc}") from exc
    packages = doc.get("package")
    if not isinstance(packages, list):
        raise ConfigError("poetry.lock has no [[package]] entries")
    notes: list[str] = []
    own = normalise(own_name) if own_name else None
    edges = _poetry_edges(packages, pyproject or {})
    lines: list[str] = []
    local: list[LocalPackage] = []
    for package in packages:
        if not isinstance(package, dict):
            continue
        name, version = package.get("name"), package.get("version")
        if not isinstance(name, str) or not isinstance(version, str):
            continue
        key = normalise(name)
        if own is not None and key == own:
            continue
        source = package.get("source") if isinstance(package.get("source"), dict) else {}
        kind = source.get("type")
        marker = _poetry_marker(package, edges.get(key))
        suffix = f" ; {marker}" if marker else ""
        if kind in ("directory", "file"):
            local_kind = "file" if kind == "file" else "editable" if package.get("develop") else "dir"
            found = _checked_local(local_kind, str(source.get("url", "")), name, marker, notes)
            if found is not None:
                local.append(found)
            continue
        if kind == "git":
            ref = source.get("resolved_reference") or source.get("reference") or ""
            url = str(source.get("url", ""))
            line = f"{name} @ git+{url}" + (f"@{ref}" if ref else "")
            subdirectory = source.get("subdirectory")
            if isinstance(subdirectory, str) and subdirectory:
                line += f"#subdirectory={subdirectory}"
        elif kind == "url":
            line = f"{name} @ {source.get('url', '')}"
        else:
            if kind == "legacy" and source.get("reference"):
                notes.append(
                    f"poetry.lock: {shown(name)} comes from the source {shown(source.get('reference'))}; "
                    "set UV_EXTRA_INDEX_URL on the control plane if it is not on PyPI"
                )
            line = f"{name}=={version}"
        refused = _refused_reference(line + suffix)
        cleaned = _clean_requirement(line + suffix)
        if cleaned is None:
            why = f"refused: {refused}" if refused else "could not be expressed as a requirement"
            notes.append(f"poetry.lock: {shown(name)} {why}, skipped")
            continue
        lines.append(cleaned)
    return lines, notes, local


def _poetry_edges(packages: list[Any], pyproject: Mapping[str, Any]) -> dict[str, list[str | None]]:
    """Normalised package name -> the markers on every dependency edge into it (None: unconditional)."""
    edges: dict[str, list[str | None]] = {}

    def add(name: str, spec: object) -> None:
        if normalise(name) == "python":
            return
        marker = None
        if isinstance(spec, dict):
            parts = []
            if isinstance(spec.get("markers"), str):
                parts.append(spec["markers"])
            if isinstance(spec.get("platform"), str):
                parts.append(f'sys_platform == "{spec["platform"]}"')
            marker = " and ".join(f"({p})" for p in parts) if parts else None
        elif isinstance(spec, list):  # multiple-constraint dependency: unconditional if any arm is
            arms = [_edge_marker(item) for item in spec]
            marker = None if any(a is None for a in arms) else " or ".join(f"({a})" for a in arms)
        edges.setdefault(normalise(name), []).append(marker)

    for package in packages:
        deps = package.get("dependencies") if isinstance(package, dict) else None
        if isinstance(deps, dict):
            for name, spec in deps.items():
                add(str(name), spec)
    tool = pyproject.get("tool") if isinstance(pyproject.get("tool"), dict) else {}
    poetry = tool.get("poetry") if isinstance(tool.get("poetry"), dict) else {}
    roots: list[Mapping[str, Any]] = []
    for table in (poetry.get("dependencies"), poetry.get("dev-dependencies")):
        if isinstance(table, dict):
            roots.append(table)
    groups = poetry.get("group")
    if isinstance(groups, dict):
        for group in groups.values():
            if isinstance(group, dict) and isinstance(group.get("dependencies"), dict):
                roots.append(group["dependencies"])
    for table in roots:
        for name, spec in table.items():
            add(str(name), spec)
    project = pyproject.get("project") if isinstance(pyproject.get("project"), dict) else {}
    for line in _strings(project.get("dependencies")):
        try:
            requirement = Requirement(line)
        except InvalidRequirement:
            continue
        edges.setdefault(normalise(requirement.name), []).append(
            str(requirement.marker) if requirement.marker else None
        )
    return edges


def _edge_marker(spec: object) -> str | None:
    if isinstance(spec, dict) and isinstance(spec.get("markers"), str):
        return spec["markers"]
    if isinstance(spec, dict) and isinstance(spec.get("platform"), str):
        return f'sys_platform == "{spec["platform"]}"'
    return None


def _poetry_marker(package: Mapping[str, Any], edges: list[str | None] | None) -> str | None:
    markers = package.get("markers")
    if isinstance(markers, str):
        return markers or None
    if isinstance(markers, dict):  # per group (lock 2.1): any group's marker admits the package
        values = [str(v) for v in markers.values() if v]
        if len(values) != len(markers) or not values:
            return None
        unique = sorted(set(values))
        return unique[0] if len(unique) == 1 else " or ".join(f"({v})" for v in unique)
    if not edges or any(e is None for e in edges):
        return None
    unique = sorted({e for e in edges if e})
    return unique[0] if len(unique) == 1 else " or ".join(f"({v})" for v in unique)


def pipfile_lock_requirements(lock_text: str) -> tuple[list[str], list[str], list[LocalPackage]]:
    """Pinned requirement lines from ``Pipfile.lock`` (``default`` and ``develop``), notes, local packages."""
    try:
        doc = json.loads(lock_text)
    except (ValueError, RecursionError) as exc:
        raise ConfigError(f"Pipfile.lock does not parse: {str(exc)[:200]}") from exc
    if not isinstance(doc, dict):
        raise ConfigError("Pipfile.lock is not a JSON object")
    lines: list[str] = []
    notes: list[str] = []
    local: list[LocalPackage] = []
    for section in ("default", "develop"):
        entries = doc.get(section)
        for name, entry in (entries if isinstance(entries, dict) else {}).items():
            if not isinstance(entry, dict):
                continue
            extras = entry.get("extras")
            extra = (
                f"[{','.join(e for e in extras if isinstance(e, str))}]"
                if isinstance(extras, list) and extras
                else ""
            )
            marker = f" ; {entry['markers']}" if isinstance(entry.get("markers"), str) else ""
            if "path" in entry or "file" in entry:
                path = str(entry.get("path") or entry.get("file") or "").removeprefix("./")
                if path in ("", "."):
                    notes.append(f"Pipfile.lock: {shown(name)} is the project itself (installed per install)")
                    continue
                kind = "editable" if entry.get("editable") else "file" if path.endswith(".whl") else "dir"
                marker_text = entry["markers"] if isinstance(entry.get("markers"), str) else None
                found = _checked_local(kind, path, str(name), marker_text, notes)
                if found is not None and found not in local:
                    local.append(found)
                continue
            if isinstance(entry.get("git"), str):
                ref = entry.get("ref")
                line = f"{name}{extra} @ git+{entry['git'].removeprefix('git+')}" + (
                    f"@{ref}" if isinstance(ref, str) else ""
                )
            else:
                version = entry.get("version")
                line = f"{name}{extra}{version if isinstance(version, str) and version != '*' else ''}"
            cleaned = _clean_requirement(line + marker)
            if cleaned is None:
                refused = _refused_reference(line + marker)
                why = f"refused: {refused}" if refused else "could not be expressed as a requirement"
                notes.append(f"Pipfile.lock: {shown(name)} {why}, skipped")
            elif cleaned not in lines:
                lines.append(cleaned)
    return lines, notes, local


# -- choosing and resolving the source --------------------------------------------------------------------


@dataclass(frozen=True, slots=True)
class EnvSource:
    """Which source describes the environment, and why it was chosen."""

    kind: EnvSourceKind
    inputs: tuple[str, ...]
    """Repo-relative files that define the environment (more may be read through includes)."""
    reason: str


@dataclass(frozen=True, slots=True)
class ResolvedEnv:
    """The pinned requirements of a checkout and how they were obtained."""

    source: EnvSource
    requirements_txt: str
    inputs_hash: str
    """sha256 over the source kind and every input file (path and bytes): ``EnvSpec.lock_hash``."""
    files: tuple[str, ...]
    """Every file read, includes and the project's metadata files included."""
    notes: tuple[str, ...] = ()
    resolved_by: str = ""
    """``uv export``, ``uv pip compile`` (``offline``/``online``), ``cache``, or the lock converted."""
    local: tuple[LocalPackage, ...] = ()
    """Packages that live in the repository, installed from the checkout (see :class:`LocalPackage`)."""


def detect_env_source(
    repo_root: Path,
    *,
    requirements: Sequence[str] = (),
    pyproject: Mapping[str, Any] | None = None,
) -> EnvSource:
    """The environment source for the checkout (see the module docstring for the order).

    Raises EnvSpecError naming the fixes when the repository has none.
    """
    doc = pyproject if pyproject is not None else load_pyproject(repo_root)
    if requirements:
        return EnvSource("requirements", tuple(requirements), "[tool.coverset] requirements")
    if _exists(repo_root, "uv.lock"):
        return EnvSource("uv.lock", ("uv.lock",), "uv.lock is committed")
    if _exists(repo_root, "poetry.lock"):
        return EnvSource("poetry", ("poetry.lock", "pyproject.toml"), "poetry.lock is committed")
    if _exists(repo_root, "Pipfile.lock"):
        return EnvSource("pipenv", ("Pipfile.lock",), "Pipfile.lock is committed")
    files = auto_requirement_files(repo_root)
    if files:
        return EnvSource("requirements", tuple(files), "requirement files found: " + ", ".join(files))
    if isinstance(doc.get("project"), dict):
        return EnvSource("pyproject", ("pyproject.toml",), "pyproject.toml has a [project] table and no lock")
    present = tuple(name for name in ("setup.cfg", "setup.py") if _exists(repo_root, name))
    if present:
        return EnvSource("setup", present, f"{' and '.join(present)} without a lock")
    raise EnvSpecError(
        f"{repo_root} has no uv.lock, poetry.lock, Pipfile.lock, requirement files, [project] table or "
        "setup.cfg/setup.py: coverset cannot tell which packages the tests need. Commit a lock "
        "(`uv lock`), or list requirement files in [tool.coverset] requirements"
    )


def _exists(repo_root: Path, name: str) -> bool:
    path = repo_root / name
    return path.is_file() or path.is_symlink()  # a symlinked lock is refused later, loudly


def resolve_environment(
    repo_root: Path,
    source: EnvSource,
    *,
    python: str,
    uv: str | None = None,
    cache_dir: Path | None = None,
    timeout_s: float = UV_TIMEOUT_S,
    offline_only: bool = False,
    pyproject: Mapping[str, Any] | None = None,
    extra_requirements: Sequence[str] = (),
) -> ResolvedEnv:
    """Pinned requirements for ``source`` (see the module docstring).

    ``extra_requirements`` (the build backend's requirements when the project gets installed) join
    the resolution for compiled sources and are appended, unpinned, to a lock's export. With
    ``offline_only`` a resolution that needs the network fails instead of going online.
    """
    doc = pyproject if pyproject is not None else load_pyproject(repo_root)
    if source.kind == "uv.lock":
        try:
            inputs_hash = sha256_file(repo_root / "uv.lock", max_bytes=MAX_LOCK_BYTES, no_follow=True)
        except FileNotFoundError:
            raise EnvSpecError(f"{repo_root} has no uv.lock") from None
        args = list(UV_EXPORT_ARGS)
        if _declares_extras(doc):
            args.append("--all-extras")
        proc = run_uv(args, uv=uv, cwd=repo_root, timeout_s=timeout_s, offline=True, cache_dir=None)
        if proc.returncode != 0:
            stderr = proc.stderr.decode("utf-8", "replace").strip()[-800:]
            raise EnvSpecError(f"uv export failed in {repo_root}: {stderr}")
        text = proc.stdout.decode("utf-8")
        lock_text = read_repo_text(repo_root, "uv.lock", MAX_LOCK_BYTES) or ""
        local, notes = uv_lock_local_packages(lock_text)
        text = _drop_refused(text, "uv.lock", notes)
        local = _existing_local(repo_root, local, notes)
        build = [*extra_requirements, *_local_build_requires(repo_root, local)]
        if build:
            text = _append_section(
                text, "build requirements for installing the project", list(dict.fromkeys(build))
            )
        text = _append_local(text, local)
        files = ("uv.lock", "pyproject.toml")
        return ResolvedEnv(source, text, inputs_hash, files, tuple(notes), "uv export", tuple(local))
    if source.kind in ("poetry", "pipenv"):
        lock_name = "poetry.lock" if source.kind == "poetry" else "Pipfile.lock"
        lock_text = read_repo_text(repo_root, lock_name, MAX_LOCK_BYTES)
        if lock_text is None:
            raise EnvSpecError(f"{repo_root} has no {lock_name}")
        if source.kind == "poetry":
            meta = project_metadata(repo_root, doc)
            lines, notes, local = poetry_lock_requirements(lock_text, doc, own_name=meta.name)
            files = ("poetry.lock", "pyproject.toml")
        else:
            lines, notes, local = pipfile_lock_requirements(lock_text)
            files = ("Pipfile.lock",)
        local = _existing_local(repo_root, local, notes)
        inputs_hash = _inputs_hash(repo_root, source.kind, files)
        header = _header(source.kind, files, python, hashlib.sha256("\n".join(lines).encode()).hexdigest())
        text = header + "".join(f"{line}\n" for line in lines)
        build = [*extra_requirements, *_local_build_requires(repo_root, local)]
        if build:
            text = _append_section(
                text, "build requirements for installing the project", list(dict.fromkeys(build))
            )
        text = _append_local(text, local)
        return ResolvedEnv(
            source, text, inputs_hash, files, tuple(notes), f"{lock_name} converted", tuple(local)
        )
    gathered = RequirementsInput()
    meta = project_metadata(repo_root, doc)
    if source.kind == "requirements":
        read_requirement_files(repo_root, source.inputs, into=gathered)
        if meta.origin:
            for line in meta.all_requirements():
                gathered.add_requirement(line, meta.origin)
            gathered.files += [f for f in meta.files if f not in gathered.files]
            gathered.notes += meta.notes
            if meta.dynamic_unresolved:
                gathered.notes.append(
                    f"{meta.origin}: the project's own dependencies could not be read statically; "
                    "the requirement files must list them"
                )
    else:
        if not meta.origin or meta.dynamic_unresolved and not meta.dependencies:
            raise EnvSpecError(
                f"{repo_root}: the project's dependencies are computed by code coverset does not run "
                f"({'; '.join(meta.notes) or 'no static metadata'}). List them in a requirements file "
                'and set [tool.coverset] requirements = ["requirements.txt", ...], or commit a lock'
            )
        for line in meta.all_requirements():
            gathered.add_requirement(line, meta.origin)
        gathered.files += meta.files
        gathered.notes += meta.notes
    local = _existing_local(repo_root, gathered.local, gathered.notes)
    for line in [*extra_requirements, *_local_build_requires(repo_root, local)]:
        gathered.add_requirement(line, "[build-system]")
    files = tuple(dict.fromkeys(gathered.files))
    inputs_hash = _inputs_hash(repo_root, source.kind, files)
    # Direct references are never handed to the resolver: it would fetch them (a URL chosen by a pull
    # request, before any approval). Only requirements by name are compiled against the operator's
    # index; the references are appended verbatim and their own dependencies are resolved when a
    # trusted build installs the environment (untrusted builds refuse them: ``direct_references``).
    named, direct = split_direct(gathered.requirements)
    compiled, how = compile_requirements(
        named,
        gathered.constraints,
        python=python,
        uv=uv,
        cache_dir=cache_dir,
        timeout_s=timeout_s,
        offline_only=offline_only,
    )
    digest = _compile_key(gathered.requirements, gathered.constraints, python)
    if direct:
        compiled = _with_direct(compiled, direct, gathered.notes)
    text = _append_local(_header(source.kind, files, python, digest) + compiled, local)
    return ResolvedEnv(source, text, inputs_hash, files, tuple(gathered.notes), how, tuple(local))


def _with_direct(compiled: str, direct: Sequence[str], notes: list[str]) -> str:
    """``compiled`` plus a section of direct references, which win over a pin of the same name.

    A compiled pin of a package that is also given by URL (``foo==1.0`` pulled in by another
    requirement, ``foo @ git+https://...`` listed directly) would make the install conflict, so the
    pin is dropped and the reference kept.
    """
    names = set()
    for line in direct:
        if line.startswith(_VCS_PREFIXES):
            continue  # a bare URL names no package before it is built
        with contextlib.suppress(InvalidRequirement):
            names.add(normalise(Requirement(line).name))
    kept = []
    for line in compiled.splitlines():
        match = re.match(r"^([A-Za-z0-9][A-Za-z0-9._-]*)", line)
        if match and normalise(match.group(1)) in names:
            notes.append(f"pin {shown(line)} dropped: the same package is given by a direct reference")
            continue
        kept.append(line)
    text = "".join(f"{line}\n" for line in kept)
    notes.append(
        f"{len(direct)} direct reference(s) not resolved on the control plane: their dependencies are "
        "installed when a trusted build creates the environment, and untrusted builds refuse them"
    )
    return _append_section(text, "direct references (not resolved by coverset)", list(direct))


def _drop_refused(text: str, origin: str, notes: list[str]) -> str:
    """``text`` (requirement lines) without the direct references :func:`_refused_reference` refuses."""
    kept = []
    for line in text.splitlines(keepends=True):
        stripped = line.strip()
        refused = None if not stripped or stripped.startswith(("#", "-")) else _refused_reference(stripped)
        if refused is not None:
            notes.append(f"{origin}: refused {shown(stripped)}: {refused}")
            continue
        kept.append(line)
    return "".join(kept)


def _existing_local(repo_root: Path, local: Sequence[LocalPackage], notes: list[str]) -> list[LocalPackage]:
    """``local`` without packages whose path is missing from the checkout (or reached by a symlink)."""
    kept = []
    for package in local:
        found = _safe_exists(repo_root, package.path)
        if found is None or (package.kind == "file") != (found == "file"):
            notes.append(f"local package {package.name} ({package.path}) is not in the checkout, skipped")
        elif found == "file" and _is_lfs_pointer(repo_root, package.path):
            notes.append(
                f"local package {package.name} ({package.path}) is a Git LFS pointer in this checkout "
                "(coverset's mirror does not fetch LFS objects), skipped"
            )
        elif package not in kept:
            kept.append(package)
    return kept


LFS_POINTER_PREFIX: Final = b"version https://git-lfs.github.com/spec/"


def _is_lfs_pointer(repo_root: Path, rel: str) -> bool:
    """Whether the file at ``rel`` is a Git LFS pointer rather than the object it stands for."""
    try:
        with open_regular(repo_root / rel, no_follow=True) as fh:
            return fh.read(len(LFS_POINTER_PREFIX)) == LFS_POINTER_PREFIX
    except (OSError, ConfigError):
        return False


def _append_local(text: str, local: Sequence[LocalPackage]) -> str:
    if not local:
        return text
    if text and not text.endswith("\n"):
        text += "\n"
    lines = "".join(f"{package.line()}\n" for package in local)
    return text + "# coverset: local packages, installed from the checkout with --no-deps\n" + lines


def _declares_extras(doc: Mapping[str, Any]) -> bool:
    project = doc.get("project") if isinstance(doc.get("project"), dict) else {}
    extras = project.get("optional-dependencies")
    return (isinstance(extras, dict) and bool(extras)) or "optional-dependencies" in _strings(
        project.get("dynamic")
    )


def _append_section(text: str, title: str, lines: Sequence[str]) -> str:
    if text and not text.endswith("\n"):
        text += "\n"
    return text + f"# coverset: {title}\n" + "".join(f"{line}\n" for line in lines)


def _header(kind: str, files: Sequence[str], python: str, digest: str) -> str:
    return (
        f"# coverset environment: source={kind} python={python}\n"
        f"# inputs: {', '.join(files) or '(none)'}\n"
        f"# resolved-input-sha256: {digest}\n"
    )


def _inputs_hash(repo_root: Path, kind: str, files: Sequence[str]) -> str:
    digest = hashlib.sha256(f"coverset-env-inputs\0{kind}\0".encode())
    for rel in sorted(files):
        data = read_repo_bytes(repo_root, rel, MAX_LOCK_BYTES)
        digest.update(rel.encode() + b"\0" + (data if data is not None else b"<missing>") + b"\0")
    return digest.hexdigest()


def _compile_key(requirements: Sequence[str], constraints: Sequence[str], python: str) -> str:
    material = json.dumps(
        {
            "v": COMPILE_VERSION,
            "args": COMPILE_ARGS,
            "python": python,
            "requirements": sorted(requirements),
            "constraints": sorted(constraints),
            "index": sorted(
                (k, os.environ[k]) for k in _PASSED_UV_ENV if k.startswith("UV_") and k in os.environ
            ),
        },
        sort_keys=True,
    )
    return hashlib.sha256(material.encode()).hexdigest()


def compile_requirements(
    requirements: Sequence[str],
    constraints: Sequence[str] = (),
    *,
    python: str,
    uv: str | None = None,
    cache_dir: Path | None = None,
    timeout_s: float = UV_TIMEOUT_S,
    offline_only: bool = False,
) -> tuple[str, str]:
    """``uv pip compile`` of ``requirements``: (pinned text, how it was obtained).

    Cached by :func:`_compile_key` under ``<cache>/requirements/``; offline first, then online.
    """
    if not requirements:
        return "", "nothing to resolve"
    if any(direct_url(line) is not None for line in [*requirements, *constraints]):
        # resolve_environment splits these out; the resolver would fetch them on the control plane
        raise EnvSpecError("internal: direct references are never handed to uv pip compile")
    root = cache_dir if cache_dir is not None else _default_cache_dir()
    key = _compile_key(requirements, constraints, python)
    cached = root / "requirements" / f"{key}.txt"
    try:
        return cached.read_text(encoding="utf-8"), "cache"
    except OSError:
        pass
    with tempfile.TemporaryDirectory(prefix="coverset-compile-") as work:
        source = Path(work) / "requirements.in"
        source.write_text("".join(f"{line}\n" for line in requirements), encoding="utf-8")
        args = [*COMPILE_ARGS, "--python-version", python, str(source)]
        if constraints:
            path = Path(work) / "constraints.txt"
            path.write_text("".join(f"{line}\n" for line in constraints), encoding="utf-8")
            args += ["--constraint", str(path)]
        uv_cache = root / "uv-cache"
        proc = run_uv(args, uv=uv, cwd=Path(work), timeout_s=timeout_s, offline=True, cache_dir=uv_cache)
        how = "uv pip compile (offline)"
        if proc.returncode != 0 and not offline_only:
            proc = run_uv(args, uv=uv, cwd=Path(work), timeout_s=timeout_s, offline=False, cache_dir=uv_cache)
            how = "uv pip compile (online)"
    if proc.returncode != 0:
        stderr = proc.stderr.decode("utf-8", "replace").strip()
        stderr = stderr.replace(str(source), "requirements.in")[-1200:]
        hint = ""
        if "source distribution" in stderr.lower() or "--no-build" in stderr:
            hint = (
                " (a dependency ships only an sdist: coverset never builds one on the control plane, "
                "because that runs its setup.py there; pin a version with a wheel or commit a uv.lock)"
            )
        elif offline_only:
            hint = " (offline only: run once with network access to fill the cache)"
        raise EnvSpecError(f"uv pip compile failed{hint}: {stderr}")
    text = proc.stdout.decode("utf-8")
    cached.parent.mkdir(parents=True, exist_ok=True)
    tmp = cached.with_name(f".{cached.name}.{os.getpid()}.tmp")
    tmp.write_text(text, encoding="utf-8")
    os.replace(tmp, cached)
    return text, how


def _default_cache_dir() -> Path:
    from coverset.executors.base import cache_root

    return cache_root()


def run_uv(
    args: Sequence[str],
    *,
    uv: str | None,
    cwd: Path,
    timeout_s: float,
    offline: bool,
    cache_dir: Path | None,
) -> subprocess.CompletedProcess[bytes]:
    """Run ``uv`` with a minimal environment: a throwaway ``HOME``, no config, no Python downloads.

    ``cache_dir`` is the uv cache (a throwaway one inside ``HOME`` when None); ``offline`` sets
    ``UV_OFFLINE``. Online runs also see the TLS, proxy and index variables in ``_PASSED_UV_ENV``.
    """
    binary = uv or shutil.which("uv")
    if binary is None:
        raise EnvSpecError("uv is not installed or not on PATH")
    with tempfile.TemporaryDirectory(prefix="coverset-uv-") as home:
        env = {
            "PATH": os.environ.get("PATH", os.defpath),
            "HOME": home,
            "UV_CACHE_DIR": str(cache_dir) if cache_dir is not None else os.path.join(home, "cache"),
            "UV_NO_CONFIG": "1",
            "UV_PYTHON_DOWNLOADS": "never",
            "LANG": "C.UTF-8",
        }
        if offline:
            env["UV_OFFLINE"] = "1"
        for name in _PASSED_UV_ENV:
            if name in os.environ and (not offline or name.startswith("UV_")):
                env[name] = os.environ[name]
        try:
            return subprocess.run(
                [binary, *args],
                cwd=cwd,
                env=env,
                stdin=subprocess.DEVNULL,
                capture_output=True,
                timeout=timeout_s,
                check=False,
            )
        except (OSError, subprocess.TimeoutExpired) as exc:
            raise EnvSpecError(f"uv {args[0]} failed: {exc}") from exc


# -- installing the project -------------------------------------------------------------------------------


@dataclass(frozen=True, slots=True)
class InstallPlan:
    """How the project itself gets into the test environment (see the module docstring)."""

    mode: InstallMode
    setting: InstallSetting
    reasons: tuple[str, ...]
    """Why this mode (for ``auto``: the signals found, or why none was needed)."""
    build_backend: str | None = None
    build_requires: tuple[str, ...] = ()
    """``[build-system] requires`` (added to the environment unless the mode is ``none``)."""
    compiled: bool = False
    warnings: tuple[str, ...] = ()


def resolve_install(
    repo_root: Path,
    setting: InstallSetting,
    *,
    packages: Sequence[str] = (),
    source_root: str = ".",
    pyproject: Mapping[str, Any] | None = None,
    meta: ProjectMetadata | None = None,
) -> InstallPlan:
    """Decide the install mode for ``setting`` (``auto`` looks for the signals in the module docstring)."""
    doc = pyproject if pyproject is not None else load_pyproject(repo_root)
    meta = meta if meta is not None else project_metadata(repo_root, doc)
    build = doc.get("build-system") if isinstance(doc.get("build-system"), dict) else None
    has_setup = _exists(repo_root, "setup.py") or _exists(repo_root, "setup.cfg")
    backend = (
        build.get("build-backend")
        if build is not None and isinstance(build.get("build-backend"), str)
        else None
    )
    if build is not None:
        requires = tuple(r for r in _strings(build.get("requires")) if _clean_requirement(r) is not None)
        backend = backend or "setuptools.build_meta:__legacy__"
    elif has_setup:
        requires, backend = DEFAULT_BUILD_REQUIRES, "setuptools.build_meta:__legacy__"
    else:
        requires = ()
    buildable = build is not None or has_setup
    compiled = meta.ext_modules or (backend or "").split(":")[0] in COMPILED_BACKENDS
    warnings: list[str] = []
    if compiled:
        warnings.append(
            "compiled extension modules: they are built when the project is installed (trusted snapshot "
            "on Modal), so a PR that changes their C/Rust sources is tested against the default "
            "branch's build until the next snapshot"
        )
    if setting in ("wheel", "editable"):
        if not buildable:
            raise EnvSpecError(
                f"[tool.coverset] install = {setting!r} needs a build backend: add [build-system] to "
                "pyproject.toml (or a setup.py/setup.cfg), or set install = 'none'"
            )
        return InstallPlan(
            setting,
            setting,
            (f"[tool.coverset] install = {setting!r}",),
            backend,
            requires,
            compiled,
            tuple(warnings),
        )
    if setting == "none":
        return InstallPlan(
            "none",
            "none",
            ("[tool.coverset] install = 'none'",),
            backend,
            requires,
            compiled,
            tuple(warnings),
        )
    if not buildable:
        return InstallPlan(
            "none", "auto", ("no build backend: the source is imported from PYTHONPATH",), None, (), False, ()
        )
    signals = _install_signals(repo_root, doc, meta, packages, source_root, compiled)
    if signals:
        return InstallPlan("wheel", "auto", tuple(signals), backend, requires, compiled, tuple(warnings))
    reasons = [f"the packages import from {source_root!r} on PYTHONPATH; nothing needs installed metadata"]
    others = [g for g in meta.entry_point_groups if g not in ("console_scripts", "gui_scripts")]
    if others:
        reasons.append(
            "entry points for other tools (" + ", ".join(others[:5]) + ") are not read by the project"
        )
    return InstallPlan("none", "auto", tuple(reasons), backend, requires, compiled, tuple(warnings))


def _install_signals(
    repo_root: Path,
    doc: Mapping[str, Any],
    meta: ProjectMetadata,
    packages: Sequence[str],
    source_root: str,
    compiled: bool,
) -> list[str]:
    signals: list[str] = []
    if compiled:
        signals.append("compiled extension modules need a build")
    consumed = _consumed_entry_point_groups(repo_root, meta.entry_point_groups, packages, source_root)
    if consumed:
        signals.append(
            "entry points the project reads itself (" + ", ".join(consumed[:5]) + ") are visible only "
            "when installed"
        )
    for package in packages:
        init = (
            f"{source_root}/{package}/__init__.py"
            if source_root not in ("", ".")
            else f"{package}/__init__.py"
        )
        try:
            text = read_repo_text(repo_root, init, MAX_SETUP_BYTES) or ""
        except ConfigError:
            continue
        if re.search(r"importlib[._]metadata|pkg_resources|\bmetadata\.version\(|\bget_distribution\(", text):
            signals.append(f"{init} reads its own installed metadata at import")
    generated = _generated_version_file(doc)
    if generated is not None and not (repo_root / generated).exists():
        signals.append(f"{generated} is generated by the build (setuptools-scm/hatch-vcs)")
    return signals


MAX_SCANNED_SOURCES: Final = 2000


def _consumed_entry_point_groups(
    repo_root: Path, groups: Sequence[str], packages: Sequence[str], source_root: str
) -> list[str]:
    """The declared entry-point groups the project's own code (or pytest) reads.

    A group another tool reads (``nbconvert.exporters``, ``docstring_to_markdown``) does not need the
    project installed for its own tests; a plugin group the project discovers itself does (its name
    appears, quoted, in a source file that calls ``entry_points``), and so does ``pytest11``, which
    registers a pytest plugin.
    """
    wanted = [g for g in groups if g not in ("console_scripts", "gui_scripts")]
    if not wanted:
        return []
    found = {g for g in wanted if g == "pytest11" or g.startswith("<")}
    pending = [g for g in wanted if g not in found]
    root = repo_root if source_root in ("", ".") else repo_root / source_root
    scanned = 0
    for package in packages:
        base = root / package
        files = (
            sorted(base.rglob("*.py"))
            if base.is_dir() and not base.is_symlink()
            else [root / f"{package}.py"]
        )
        for path in files:
            if not pending or scanned >= MAX_SCANNED_SOURCES:
                break
            scanned += 1
            try:
                text = path.read_text(encoding="utf-8", errors="replace") if path.is_file() else ""
            except OSError:
                continue
            if "entry_points" not in text:  # also matches iter_entry_points
                continue
            for group in list(pending):
                if f'"{group}"' in text or f"'{group}'" in text:
                    found.add(group)
                    pending.remove(group)
    return [g for g in wanted if g in found]


def _generated_version_file(doc: Mapping[str, Any]) -> str | None:
    tool = doc.get("tool") if isinstance(doc.get("tool"), dict) else {}
    scm = tool.get("setuptools_scm")
    if isinstance(scm, dict):
        for key in ("version_file", "write_to"):
            if isinstance(scm.get(key), str):
                return scm[key]
    hatch = tool.get("hatch") if isinstance(tool.get("hatch"), dict) else {}
    hooks = hatch.get("build", {}).get("hooks", {}) if isinstance(hatch.get("build"), dict) else {}
    vcs = hooks.get("vcs") if isinstance(hooks, dict) else None
    if isinstance(vcs, dict) and isinstance(vcs.get("version-file"), str):
        return vcs["version-file"]
    return None


FALLBACK_WRITER: Final = r'''
import os, sys, sysconfig
source, site = sys.argv[1], sys.argv[2]
if site == "-":
    site = sysconfig.get_paths()["purelib"]
generated = []
for name in sorted(os.listdir(source)) if os.path.isdir(source) else []:
    installed = os.path.join(site, name)
    if name.startswith(".") or not os.path.isdir(installed) or not os.path.isdir(os.path.join(source, name)):
        continue
    for folder, dirs, files in os.walk(installed):
        dirs[:] = [d for d in dirs if d != "__pycache__"]
        rel = os.path.relpath(folder, site)
        for file in files:
            if file.endswith(".py") and file != "__init__.py" and not os.path.exists(os.path.join(source, rel, file)):
                generated.append(".".join(rel.split(os.sep) + [file[:-3]]))
hook = """\"\"\"Written by coverset: imports from the installed copy only what the source tree cannot provide.

PYTHONPATH puts the checkout first, so a package imports from source and its compiled extension modules,
and the modules its build generated, are not found there. This finder runs after every other one and
answers only for those: an extension module (by suffix) or a module listed in GENERATED.
\"\"\"
import importlib.machinery as _machinery
import os as _os
import sys as _sys

SITE = _os.path.dirname(_os.path.abspath(__file__))
GENERATED = frozenset(%r)


class CoversetInstalledFallback:
    @classmethod
    def find_spec(cls, fullname, path=None, target=None):
        parent, _, _ = fullname.rpartition(".")
        if not parent:
            return None
        spec = _machinery.PathFinder.find_spec(fullname, [_os.path.join(SITE, *parent.split("."))])
        origin = getattr(spec, "origin", None) or ""
        if spec is not None and (fullname in GENERATED or origin.endswith(tuple(_machinery.EXTENSION_SUFFIXES))):
            return spec
        return None


if not any(getattr(f, "__name__", "") == "CoversetInstalledFallback" for f in _sys.meta_path):
    _sys.meta_path.append(CoversetInstalledFallback)
""" % (sorted(generated),)
with open(os.path.join(site, "_coverset_fallback.py"), "w", encoding="utf-8") as fh:
    fh.write(hook)
with open(os.path.join(site, "_coverset_fallback.pth"), "w", encoding="utf-8") as fh:
    fh.write("import _coverset_fallback\n")
print("coverset: fallback hook written to", site, "generated:", len(generated))
'''
"""``python -c FALLBACK_WRITER <source dir> <site dir or ->``: writes the import hook (a module and the
``.pth`` that loads it) into the site directory the project was installed into."""


def snapshot_install_commands(
    mode: InstallMode,
    *,
    repo_dir: str,
    source_dir: str,
    python: str = "python",
    local: Sequence[LocalPackage] = (),
) -> list[list[str]]:
    """Commands that install the project inside a sandbox with no network (Modal's snapshot step).

    The build backend is already in the environment (``build_requires``), so pip builds without
    isolation and without an index; ``--no-deps`` keeps the locked environment untouched. Local
    packages go first (the project may import them at build time), regular ones as
    ``name @ file://...`` requirements so their markers pick the right wheel, editable ones with
    ``-e`` so they follow the checkout a pull request puts in ``repo_dir``.
    """
    pip = [python, "-m", "pip", "install", "--no-deps", "--no-build-isolation", "--no-index", "--quiet"]
    commands: list[list[str]] = []
    regular = [package.requirement(repo_dir) for package in local if package.kind != "editable"]
    editable = [
        arg for package in local if package.kind == "editable" for arg in ("-e", f"{repo_dir}/{package.path}")
    ]
    if regular or editable:
        commands.append([*pip, *regular, *editable])
    if mode != "none":
        commands.append([*pip, *(["-e"] if mode == "editable" else []), repo_dir])
    if commands:
        commands.append([python, "-c", FALLBACK_WRITER, source_dir, "-"])
    return commands
