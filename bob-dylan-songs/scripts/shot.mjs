import { chromium } from 'playwright-core';
const url = process.argv[2] || 'http://localhost:5173/';
const out = process.argv[3] || 'shot.png';
const b = await chromium.launch({ executablePath: '/opt/pw-browsers/chromium-1194/chrome-linux/chrome', args: ['--use-gl=angle','--use-angle=swiftshader','--enable-unsafe-swiftshader','--ignore-gpu-blocklist'] }).catch(async e => { console.error('launch fail', e.message); return chromium.launch({ args: ['--use-gl=angle','--use-angle=swiftshader','--enable-unsafe-swiftshader'] }); });
const p = await b.newPage({ viewport: { width: 1280, height: 800 }, deviceScaleFactor: 1 });
p.on('console', m => console.log('[console]', m.type(), m.text()));
p.on('pageerror', e => console.log('[pageerror]', e.message));
await p.goto(url, { waitUntil: 'load' });
await p.waitForFunction(() => window.__ready === true, null, { timeout: 30000 }).catch(() => console.log('not ready'));
await p.waitForTimeout(500);
await p.screenshot({ path: out });
console.log('saved', out);
await b.close();
